-- ЛР9. Схема PostgreSQL для проекта планирования графика отпусков.
-- Повторный запуск: удаляет только таблицы учебной схемы этого проекта.
-- Выполнять только в отдельной учебной БД course_vacation_planning.

DROP TABLE IF EXISTS vacation_requests CASCADE;
DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS sites CASCADE;

CREATE TABLE sites (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(160) NOT NULL,
    login         VARCHAR(80) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(30) NOT NULL
                  CHECK (role IN ('HRSpecialist', 'Planner', 'Manager'))
);

CREATE TABLE vacation_requests (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number             VARCHAR(20) NOT NULL UNIQUE,
    title              VARCHAR(80) NOT NULL
                       CHECK (char_length(btrim(title)) BETWEEN 5 AND 80),
    description        VARCHAR(500) NOT NULL
                       CHECK (char_length(btrim(description)) BETWEEN 10 AND 500),
    site_id            INTEGER NOT NULL REFERENCES sites(id)
                       ON UPDATE CASCADE ON DELETE RESTRICT,
    status             TEXT NOT NULL
                       CHECK (status IN ('New', 'InProgress', 'Closed', 'Cancelled')),
    created_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by_user_id INTEGER NOT NULL REFERENCES users(id)
                       ON UPDATE CASCADE ON DELETE RESTRICT,
    assignee_user_id   INTEGER NULL REFERENCES users(id)
                       ON UPDATE CASCADE ON DELETE RESTRICT
);

-- Ускоряет выборки заявок по статусу (например, только New).
CREATE INDEX vacation_requests_status_idx
    ON vacation_requests (status);

-- Ускоряет выборки и соединения заявок по участку предприятия.
CREATE INDEX vacation_requests_site_id_idx
    ON vacation_requests (site_id);

-- Дополнительный индекс для сортировки/выборки по дате создания.
CREATE INDEX vacation_requests_created_at_idx
    ON vacation_requests (created_at DESC);

-- Дополнительный индекс для поиска заявок назначенного исполнителя.
CREATE INDEX vacation_requests_assignee_user_id_idx
    ON vacation_requests (assignee_user_id);
